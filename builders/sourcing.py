"""Fetch, normalize, hash and compare canonical sources. No LLM involved.

Change detection is deterministic: a source changed iff the sha256 of its normalized
text differs from the value recorded in builders/sources.lock.yaml (or it has no lock
entry yet). Builders fetch at build time only.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol
from urllib.request import Request, urlopen

import yaml

from compliance_common.text import normalize  # noqa: F401  (re-exported: builders and tests import it from here)

BUILDERS_DIR = Path(__file__).resolve().parent
REGISTRY_PATH = BUILDERS_DIR / "sources.yaml"
LOCK_PATH = BUILDERS_DIR / "sources.lock.yaml"
ECFR = "https://www.ecfr.gov/api/versioner/v1"
USER_AGENT = "Mozilla/5.0 (compliance_poc source check)"


class ManualSource(Exception):
    """The source cannot be fetched by a script; a human must refresh its snapshot."""


@dataclass
class Fetched:
    raw: bytes
    text: str          # normalized text that is hashed
    as_of: str         # upstream date the text reflects
    url: str

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.text.encode("utf-8")).hexdigest()


class Fetcher(Protocol):
    def fetch(self, source: dict[str, Any]) -> Fetched: ...


class LiveFetcher:
    """Fetch over the network (build time only)."""

    def __init__(self, timeout: float = 60.0) -> None:
        self.timeout = timeout
        self._ecfr_date: str | None = None

    def _get(self, url: str) -> bytes:
        request = Request(url, headers={"User-Agent": USER_AGENT, "Accept-Encoding": "gzip"})
        with urlopen(request, timeout=self.timeout) as response:
            body = response.read()
            if response.headers.get("Content-Encoding") == "gzip":
                import gzip
                body = gzip.decompress(body)
            return body

    def ecfr_date(self) -> str:
        if self._ecfr_date is None:
            titles = json.loads(self._get(f"{ECFR}/titles.json"))["titles"]
            self._ecfr_date = next(t for t in titles if t["number"] == 12)["up_to_date_as_of"]
        return self._ecfr_date

    def fetch(self, source: dict[str, Any]) -> Fetched:
        kind = source["kind"]
        if kind == "manual":
            raise ManualSource(source.get("note", "refresh manually"))
        if kind == "ecfr_section":
            date = self.ecfr_date()
            url = f"{ECFR}/full/{date}/title-{source['title']}.xml?part={source['part']}&section={source['section']}"
            raw = self._get(url)
            return Fetched(raw, normalize(raw), date, url)
        if kind == "ecfr_appendix":
            from urllib.parse import quote
            date = self.ecfr_date()
            url = f"{ECFR}/full/{date}/title-{source['title']}.xml?part={source['part']}&appendix={quote(source['appendix'])}"
            raw = self._get(url)
            return Fetched(raw, normalize(raw), date, url)
        if kind == "url":
            raw = self._get(source["url"])
            return Fetched(raw, normalize(raw, source.get("select_regex")), "", source["url"])
        raise ValueError(f"unknown source kind {kind!r}")


def load_registry(path: Path = REGISTRY_PATH) -> dict[str, Any]:
    registry = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(registry.get("domains"), dict):
        raise ValueError("sources.yaml must define 'domains'")
    return registry


def load_lock(path: Path = LOCK_PATH) -> dict[str, Any]:
    if not path.exists():
        return {"sources": {}}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {"sources": {}}


def save_lock(lock: dict[str, Any], path: Path = LOCK_PATH) -> None:
    header = "# Generated by `python -m builders.build lock|run`. sha256 of NORMALIZED source text per registry source.\n"
    path.write_text(header + yaml.safe_dump(lock, sort_keys=True), encoding="utf-8")


@dataclass
class SourceStatus:
    source_id: str
    state: str               # unchanged | changed | new | manual | error
    detail: str = ""
    fetched: Fetched | None = None


@dataclass
class DomainStatus:
    domain: str
    sources: list[SourceStatus] = field(default_factory=list)

    @property
    def changed(self) -> list[SourceStatus]:
        return [s for s in self.sources if s.state in ("changed", "new")]

    @property
    def needs_build(self) -> bool:
        return bool(self.changed)


def check(registry: dict[str, Any], lock: dict[str, Any], fetcher: Fetcher, domains: list[str] | None = None) -> list[DomainStatus]:
    """Compare every registry source against the lock. Reads the network, writes nothing."""
    selected = domains or list(registry["domains"])
    unknown = [d for d in selected if d not in registry["domains"]]
    if unknown:
        raise ValueError(f"unknown domains {unknown}; registry has {list(registry['domains'])}")
    statuses = []
    for name in selected:
        status = DomainStatus(name)
        for source in registry["domains"][name]["sources"]:
            sid = source["id"]
            try:
                fetched = fetcher.fetch(source)
            except ManualSource as exc:
                status.sources.append(SourceStatus(sid, "manual", str(exc)))
                continue
            except Exception as exc:  # network or layout failure is reported, never treated as "unchanged"
                status.sources.append(SourceStatus(sid, "error", f"{type(exc).__name__}: {exc}"))
                continue
            locked = lock.get("sources", {}).get(sid)
            if locked is None:
                status.sources.append(SourceStatus(sid, "new", "no lock entry", fetched))
            elif locked["normalized_sha256"] != fetched.sha256:
                status.sources.append(SourceStatus(sid, "changed", f"{locked['normalized_sha256'][:12]} -> {fetched.sha256[:12]}", fetched))
            else:
                status.sources.append(SourceStatus(sid, "unchanged", "", fetched))
        statuses.append(status)
    return statuses


def lock_entry(source: dict[str, Any], fetched: Fetched) -> dict[str, Any]:
    return {"domain_snapshot": source.get("snapshot", ""), "normalized_sha256": fetched.sha256,
            "as_of": fetched.as_of, "url": fetched.url}

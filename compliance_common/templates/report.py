"""The review report, assembled by code from the role results. The model writes at most one short summary.

`build_report` puts together, in this order: the summary (the model's, if it passed the checks; else code's), the results table, the
loan-officer sheets (what each customer file still needs, and what to refer to compliance), the examiner findings by regime, and the
auditor's cross-regime findings. Nothing in it is generated by a model except the summary, so nothing in it can drop or soften a finding.
A role that returned no result is listed as such, never as a pass.
"""
from __future__ import annotations

import json
from typing import Any

from .loan_officer import CUSTOMER_TITLE, REFER_TITLE

SUMMARY_WORD_LIMIT = 150
AUDITOR = "auditor"


def _templates(result: Any) -> dict[str, Any] | None:
    templates = result.get("response_templates") if isinstance(result, dict) else None
    return templates if isinstance(templates, dict) else None


def has_templates(results: dict[str, Any]) -> bool:
    """True when at least one role result carries `response_templates`; only then can code assemble a report."""
    return any(_templates(r) for r in results.values())


def _name(key: str, result: dict[str, Any]) -> str:
    return str((result.get("agent_metadata") or {}).get("agent_name") or key.upper())


def _classification(result: dict[str, Any]) -> str:
    return str((result.get("domain_determination") or {}).get("classification", ""))


def _result(result: dict[str, Any]) -> str:
    return str((result.get("determination_status") or {}).get("result", ""))


def digest(results: dict[str, Any]) -> dict[str, Any]:
    """What the summary model is shown: each role's classification, result and finding ids, and the counts of sheet items. Not the report."""
    out: dict[str, Any] = {}
    for key, result in results.items():
        templates = _templates(result)
        if templates is None:
            out[key] = {"status": "no result", "detail": result.get("failure") if isinstance(result, dict) else "the role returned no structured result"}
            continue
        sheet = templates.get("loan_officer") or {}
        out[key] = {"classification": _classification(result), "result": _result(result),
                    "findings": [rule_id for p in templates.get("examiner", []) for rule_id in p["rule_ids"]],
                    "needed_from_customer": len(sheet.get("needed_from_customer", [])), "refer_to_compliance": len(sheet.get("refer_to_compliance", []))}
    return out


def check_summary(text: Any, source: dict[str, Any]) -> list[str]:
    """Violations in a model summary (empty list = acceptable): one short plain paragraph that adds no number, date or id the digest lacks."""
    from ..narrative import grounding_violations          # local import: narrative imports the templates package
    if not isinstance(text, str) or not text.strip():
        return ["the summary is empty"]
    out = []
    words = len(text.split())
    if words > SUMMARY_WORD_LIMIT:
        out.append(f"the summary has {words} words; the limit is {SUMMARY_WORD_LIMIT}")
    if "```" in text or text.lstrip().startswith(("{", "[", "|")):
        out.append("the summary must be plain text")
    return out + grounding_violations(text, {}, source, "", cross_regime=True)


def clean_summary(text: str) -> str:
    """Drop heading lines a model may add; the report supplies its own heading."""
    return "\n".join(line for line in text.strip().splitlines() if not line.lstrip().startswith("#")).strip()


def code_summary(results: dict[str, Any]) -> str:
    """A short, accurate summary written from the results alone (used when the model's is missing or fails a check)."""
    shown = digest(results)
    ok = {k: v for k, v in shown.items() if "result" in v}
    missing = [k for k, v in shown.items() if "result" not in v]
    open_items = [k for k, v in ok.items() if v["findings"]]
    parts = ["Results by regime: " + "; ".join(f"{k.upper()} {v['result']}" for k, v in ok.items()) + "."]
    parts.append(("Findings are open in " + ", ".join(k.upper() for k in open_items) + ".") if open_items else "No regime has an open finding.")
    if missing:
        parts.append("No result was returned for " + ", ".join(k.upper() for k in missing) + "; do not read that as a pass.")
    parts.append("The loan-officer sheets list what each customer file still needs and what to refer to compliance. The examiner section explains every finding.")
    return " ".join(parts)


def _sheet(results: dict[str, Any]) -> list[str]:
    needed, refer = ["### " + CUSTOMER_TITLE, ""], ["### " + REFER_TITLE, ""]
    any_needed = any_refer = False
    for key, result in results.items():
        sheet = (_templates(result) or {}).get("loan_officer") or {}
        name = _name(key, result) if isinstance(result, dict) else key.upper()
        if sheet.get("needed_from_customer"):
            any_needed = True
            needed += [f"**{name}**", ""]
            for item in sheet["needed_from_customer"]:
                subject = f" (subject {item['subject_id']})" if item.get("subject_id") else ""
                needed.append(f"- **{item['label']}**{subject}: {item['text']}")
            needed.append("")
        if sheet.get("refer_to_compliance"):
            any_refer = True
            refer += [f"**{name}**", ""]
            for item in sheet["refer_to_compliance"]:
                subject = f" (subject {item['subject_id']})" if item.get("subject_id") else ""
                refer.append(f"- {item['text']}{subject} Who: {item.get('who', 'compliance reviewer')}.")
            refer.append("")
    return (needed if any_needed else needed + ["Nothing is needed from the customer.", ""]) + (refer if any_refer else refer + ["Nothing to refer.", ""])


def _examiner(results: dict[str, Any], keys: list[str]) -> list[str]:
    out: list[str] = []
    for key in keys:
        result = results[key]
        paragraphs = (_templates(result) or {}).get("examiner") or []
        if not paragraphs:
            continue
        out += [f"### {_name(key, result)}: {_classification(result)} ({_result(result)})", ""]
        for p in paragraphs:
            out += [f"{p['text']} [{p['rule_id']}; {p['source']}]", ""]
    return out


def build_report(results: dict[str, Any], summary: str | None = None) -> str:
    """The Markdown report for a set of role results. `summary` is the model's, already checked; None means code writes it."""
    summary = clean_summary(summary) if summary else code_summary(results)
    roles = list(results)
    domain_keys = [k for k in roles if k != AUDITOR]
    lines = ["# Compliance Review Summary", "", "## Summary", "", summary, "", "## Results", "", "| Role | Classification | Result | Findings |", "| --- | --- | --- | --- |"]
    for key in roles:
        result = results[key]
        templates = _templates(result)
        if templates is None:
            lines.append(f"| {key.upper()} | no result | no result | not reviewed |")
        else:
            lines.append(f"| {_name(key, result)} | {_classification(result)} | {_result(result)} | {sum(len(p['rule_ids']) for p in templates['examiner'])} |")
    lines += ["", "## Loan officer sheet", ""] + _sheet(results)
    lines += ["## Examiner findings", ""] + (_examiner(results, domain_keys) or ["No regime has an open finding.", ""])
    if AUDITOR in results:
        lines += ["## Cross-regime findings", ""] + (_examiner(results, [AUDITOR]) or ["The auditor reported no cross-regime finding.", ""])
    missing = [k for k in roles if _templates(results[k]) is None]
    if missing:
        lines += ["## Roles with no result", ""] + [f"- {k.upper()}: {_why(results[k])}" for k in missing] + [""]
    return "\n".join(lines).rstrip() + "\n"


def _why(result: Any) -> str:
    if isinstance(result, dict):
        return str(result.get("failure") or result.get("status") or "the role returned no result with templates")
    return "the role returned text, not a structured result"
